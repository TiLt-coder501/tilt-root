/// Whether the menu is shown in Portuguese (the default): read once
inline bool on() {
    static const bool v = [] {
        const char* e = std::getenv("RX_VK_MENU_LANG");
        return !(e && (e[0] == 'e' || e[0] == 'E'));
    }();
    return v;
}
/// The text in Portuguese, or nullptr when the table has none for it
inline const char* find(const char* en) {
    if (!en || !*en || !on()) return nullptr;
    for (const Pair& p : kText)
        if (!std::strcmp(p.en, en)) return p.pt;
    return nullptr;
}
/// The text in Portuguese, or the text itself
inline const char* tr(const char* en) {
    const char* pt = find(en);
    return pt ? pt : en;
}
